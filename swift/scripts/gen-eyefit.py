#!/usr/bin/env python3
"""Writes Sources/HermesAvatar/EyefitTable.swift from ../golden/eyefit.json (the TypeScript engine's table).
The golden test re-reads the JSON and checks this file still matches it."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
g = os.path.join(here, '..', 'golden', 'eyefit.json')
if not os.path.exists(g): g = os.path.join(here, '..', '..', 'golden', 'eyefit.json')
d = json.load(open(g))
lines = ['// GENERATED by swift/scripts/gen-eyefit.py from golden/eyefit.json. Do not edit.', '',
         'let EYEFIT_TABLE: [String: [String: Point]] = [']
for shape, per in d['shapes'].items():
    lines.append(f'    "{shape}": [')
    for k, v in per.items():
        lines.append(f'        "{k}": Point(x: {v["x"]!r}, y: {v["y"]!r}),')
    lines.append('    ],')
lines.append(']')
open(os.path.join(here, '..', 'Sources', 'HermesAvatar', 'EyefitTable.swift'), 'w').write('\n'.join(lines) + '\n')
